#!/bin/sh
# Regenerates THIRD_PARTY_NOTICES.md; run after changing dependencies or copying code.
set -eu

root=$(CDPATH='' cd -- "$(dirname -- "$0")/.." && pwd)
cd "$root"
export GOFLAGS=-tags=novulkan
modcache=$(mise exec -- go env GOMODCACHE)
out=THIRD_PARTY_NOTICES.md
desktop=$(mktemp)
trap 'rm -f "$desktop"' EXIT

license_file() {
    for name in LICENSE LICENSE.md LICENSE.txt LICENCE COPYING UNLICENSE; do
        if [ -f "$1/$name" ]; then
            printf '%s\n' "$1/$name"
            return 0
        fi
    done
    return 1
}

# why: the module cache escapes upper-case letters as !lower.
escape() {
    printf '%s' "$1" | sed 's/\([A-Z]\)/!\1/g' | tr '[:upper:]' '[:lower:]'
}

{
    cat docs/credits-copied.md
    printf '\n## Go modules linked into pitwall\n\n'
    printf 'Generated by `scripts/notices.sh` from `go list -deps ./cmd/pitwall` for Linux, macOS and Windows, and `./cmd/pitwall-phone` for those and Android.\n'
    for goos in linux darwin windows; do
        CGO_ENABLED=1 GOOS=$goos mise exec -- go list -deps -f '{{if .Module}}{{.Module.Path}} {{.Module.Version}}{{end}}' ./cmd/pitwall
    done | sort -u >"$desktop"
    for goos in linux darwin windows android; do
        CGO_ENABLED=1 GOOS=$goos mise exec -- go list -deps -f '{{if .Module}}{{.Module.Path}} {{.Module.Version}}{{end}}' ./cmd/pitwall-phone
    done | cat - "$desktop" |
        sort -u | grep -v '^github.com/quanticstudios/pitwall' |
        while read -r path ver; do
            case $path in
            github.com/charmbracelet/x/vt) dir=third_party/x-vt ;;
            gioui.org/x) dir=third_party/gioui.org-x ;;
            *) dir="$modcache/$(escape "$path")@$ver" ;;
            esac
            printf '\n### %s %s\n\n' "$path" "$ver"
            if ! grep -qx "$path $ver" "$desktop"; then
                printf 'Linked into the Android app (`cmd/pitwall-phone`) only.\n\n'
            fi
            if file=$(license_file "$dir"); then
                printf '```text\n'
                cat "$file"
                printf '```\n'
            else
                printf 'No license file found in the module; see its repository.\n'
            fi
        done
} >"$out"
printf 'Wrote %s\n' "$out"
